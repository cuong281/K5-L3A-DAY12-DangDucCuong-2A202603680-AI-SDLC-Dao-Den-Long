#!/usr/bin/env node
// Runs every scenarios/<case>/ through the real headless CLI TWICE, checks
// determinism (byte-identical) and the hand-computed expectations in case.json,
// then writes outputs + a summary to docs/proof/<phase>/.
// Usage: node tools/proof.js [phase-1]
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const phase = process.argv[2] || 'phase-1';
const outDir = path.join(root, 'docs', 'proof', phase, 'headless');
fs.mkdirSync(outDir, { recursive: true });
const scenDir = path.join(root, 'scenarios');

const sub = (actual, expected) =>
  Object.entries(expected).every(([k, v]) => JSON.stringify(actual?.[k]) === JSON.stringify(v));

function runOnce(dir, c, out) {
  const args = ['headless.js', '--seed', String(c.seed), '--night', '1', '--ticks', String(c.ticks), '--out', out];
  if (fs.existsSync(path.join(dir, 'scenario.json'))) args.push('--scenario', path.join(dir, 'scenario.json'));
  if (fs.existsSync(path.join(dir, 'inputs.json'))) args.push('--inputs', path.join(dir, 'inputs.json'));
  if (c.snapshot_every) args.push('--snapshot-every', String(c.snapshot_every));
  const r = spawnSync(process.execPath, args, { cwd: root, encoding: 'utf8' });
  return { code: r.status, stderr: r.stderr, cmd: 'node ' + args.map((a) => path.isAbsolute(a) ? path.relative(root, a).replaceAll('\\', '/') : a).join(' ') };
}

const rows = [];
let failed = 0;
for (const name of fs.readdirSync(scenDir).sort()) {
  const dir = path.join(scenDir, name);
  if (!fs.existsSync(path.join(dir, 'case.json'))) continue;
  const c = JSON.parse(fs.readFileSync(path.join(dir, 'case.json'), 'utf8'));
  const outA = path.join(outDir, `${name}.jsonl`);
  const outB = path.join(outDir, `${name}.run2.jsonl`);
  const a = runOnce(dir, c, outA);
  const b = runOnce(dir, c, outB);
  const problems = [];
  if (a.code !== 0) problems.push(`exit ${a.code}: ${a.stderr.trim()}`);
  const rawA = fs.existsSync(outA) ? fs.readFileSync(outA, 'utf8') : '';
  const rawB = fs.existsSync(outB) ? fs.readFileSync(outB, 'utf8') : '';
  const deterministic = rawA.length > 0 && rawA === rawB;
  if (!deterministic) problems.push('run 1 != run 2 (non-deterministic)');
  fs.rmSync(outB, { force: true });
  const lines = rawA.trim().split('\n').filter(Boolean).map((l) => JSON.parse(l));
  const end = lines.at(-1);
  const events = lines.filter((l) => l.type === 'event');
  if (end?.type !== 'end') problems.push('last line is not "end"');
  if (c.expect?.end && !sub(end, c.expect.end)) problems.push(`end ${JSON.stringify(end)} != expected ${JSON.stringify(c.expect.end)}`);
  for (const e of c.expect?.events || []) {
    if (!events.some((x) => x.tick === e.tick && x.name === e.name && (!e.data || JSON.stringify(x.data) === JSON.stringify(e.data))))
      problems.push(`missing event ${JSON.stringify(e)}`);
  }
  for (const n of c.expect?.no_events || []) if (events.some((x) => x.name === n)) problems.push(`unexpected event ${n}`);
  if (problems.length) failed++;
  rows.push({ name, why: c.why, cmd: a.cmd, end, deterministic, problems, nEvents: events.length });
}

const md = [
  `# Headless proof — ${phase}`,
  '',
  'Generated by `npm run proof` (tools/proof.js). Each case runs the real headless CLI twice;',
  'outputs are byte-compared (determinism) and checked against hand-computed expectations in `scenarios/<case>/case.json`.',
  'Do not edit outputs by hand — re-run the script.',
  '',
  '| Case | Result | Deterministic | End line | Why / expectation |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| \`${r.name}\` | ${r.problems.length ? '**FAIL** ' + r.problems.join('; ') : 'PASS'} | ${r.deterministic ? 'yes' : 'NO'} | \`${JSON.stringify(r.end)}\` | ${r.why} |`),
  '',
  '## Commands',
  '',
  ...rows.map((r) => `- \`${r.name}\`: \`${r.cmd.replace(/--out \S+/, `--out docs/proof/${phase}/headless/${r.name}.jsonl`)}\``),
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'docs', 'proof', phase, 'headless-summary.md'), md);
console.log(md);
console.log(failed ? `\n${failed} case(s) FAILED` : '\nall cases PASS');
process.exit(failed ? 1 : 0);
